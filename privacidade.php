                    <h2 id="seguranca">10. Medidas de Segurança Técnicas e Organizacionais</h2>
                    <p>A ANGONUEVE implementa um conjunto abrangente de medidas de segurança técnicas, físicas e organizacionais para proteger os dados pessoais contra acessos não autorizados, alterações, divulgações, destruições acidentais ou ilícitas, perdas ou qualquer outra forma de tratamento ilícito, em conformidade com o artigo 17.º da Lei n.º 22/11.</p>

                    <h3>10.1. Medidas Técnicas</h3>
                    <ul>
                        <li><strong>Encriptação de comunicações:</strong> todas as comunicações entre o navegador do utilizador e os nossos servidores são encriptadas utilizando protocolo SSL/TLS (HTTPS) com certificados válidos;</li>
                        <li><strong>Encriptação em repouso:</strong> os dados pessoais armazenados nos nossos servidores são encriptados utilizando algoritmos de encriptação robustos (AES-256);</li>
                        <li><strong>Firewalls e sistemas de detecção de intrusão:</strong> implementamos firewalls de rede e sistemas de detecção/prevenção de intrusão (IDS/IPS) para monitorizar e bloquear acessos não autorizados;</li>
                        <li><strong>Controlo de acessos:</strong> implementamos controlo de acesso baseado em funções (RBAC), garantindo que apenas colaboradores autorizados acedem a dados pessoais estritamente necessários ao desempenho das suas funções;</li>
                        <li><strong>Autenticação multifactor (MFA):</strong> para acessos administrativos a sistemas que contêm dados pessoais;</li>
                        <li><strong>Monitorização e registo de acessos:</strong> mantemos registos detalhados de todos os acessos a sistemas que contêm dados pessoais;</li>
                        <li><strong>Actualizações e patches de segurança:</strong> todos os sistemas são mantidos actualizados com os mais recentes patches de segurança;</li>
                        <li><strong>Backups regulares:</strong> são realizadas cópias de segurança periódicas dos dados, armazenadas de forma segura e encriptada;</li>
                        <li><strong>Testes de penetração:</strong> realizamos testes de penetração periódicos para identificar e corrigir vulnerabilidades de segurança.</li>
                    </ul>

                    <h3>10.2. Medidas Organizacionais</h3>
                    <ul>
                        <li><strong>Políticas e procedimentos:</strong> mantemos políticas e procedimentos internos de segurança da informação e protecção de dados;</li>
                        <li><strong>Formação e sensibilização:</strong> todos os colaboradores recebem formação regular em matéria de protecção de dados e segurança da informação;</li>
                        <li><strong>Acordos de confidencialidade:</strong> todos os colaboradores e subcontratantes estão vinculados a acordos de confidencialidade;</li>
                        <li><strong>Gestão de incidentes:</strong> dispomos de um plano de resposta a incidentes de segurança para garantir uma acção rápida e eficaz em caso de violação de dados;</li>
                        <li><strong>Avaliações de impacto:</strong> realizamos avaliações de impacto sobre a protecção de dados (AIPD) para operações de tratamento que apresentem elevado risco para os direitos e liberdades dos titulares;</li>
                        <li><strong>Princípio da privacidade desde a concepção:</strong> a protecção de dados é integrada em todos os novos sistemas, processos e produtos desde a sua fase de concepção (privacy by design).</li>
                    </ul>

