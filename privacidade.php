                    <h2 id="direitos">12. Direitos do Titular dos Dados</h2>
                    <p>Nos termos da Lei n.º 22/11 de 17 de Junho (Lei da Protecção de Dados Pessoais), o titular dos dados tem os seguintes direitos, que podem ser exercidos a qualquer momento:</p>

                    <h3>12.1. Direito de Acesso (art. 11.º)</h3>
                    <p>O titular tem o direito de obter da ANGONUEVE a confirmação de que os dados pessoais que lhe digam respeito são ou não objecto de tratamento e, se for esse o caso, o direito de aceder aos mesmos e às seguintes informações:</p>
                    <ul>
                        <li>As finalidades do tratamento;</li>
                        <li>As categorias de dados pessoais em causa;</li>
                        <li>Os destinatários ou categorias de destinatários a quem os dados foram ou serão divulgados;</li>
                        <li>O período de conservação previsto;</li>
                        <li>A existência do direito de solicitar rectificação, eliminação ou limitação do tratamento;</li>
                        <li>O direito de apresentar reclamação à autoridade de controlo;</li>
                        <li>A origem dos dados, quando não recolhidos directamente junto do titular.</li>
                    </ul>

                    <h3>12.2. Direito de Rectificação (art. 12.º)</h3>
                    <p>O titular tem o direito de obter, sem demora injustificada, a rectificação dos dados pessoais inexactos ou incompletos que lhe digam respeito, mediante declaração escrita ou através da Área do Cliente.</p>

                    <h3>12.3. Direito à Eliminação («Direito ao Esquecimento») (art. 13.º)</h3>
                    <p>O titular tem o direito de obter a eliminação dos seus dados pessoais quando se aplique um dos seguintes motivos:</p>
                    <ul>
                        <li>Os dados já não são necessários para a finalidade que motivou a sua recolha;</li>
                        <li>O titular retira o consentimento em que se baseia o tratamento;</li>
                        <li>O titular opõe-se ao tratamento e não existem interesses legítimos prevalecentes;</li>
                        <li>Os dados foram tratados ilicitamente;</li>
                        <li>Os dados devem ser eliminados para cumprimento de uma obrigação legal.</li>
                    </ul>
                    <p><strong>Excepções:</strong> A ANGONUEVE pode recusar a eliminação quando o tratamento for necessário para o cumprimento de obrigação legal, para a defesa de direitos num processo judicial, ou por razões de interesse público.</p>

                    <h3>12.4. Direito à Limitação do Tratamento (art. 14.º)</h3>
                    <p>O titular tem o direito de obter a limitação do tratamento dos seus dados pessoais quando:</p>
                    <ul>
                        <li>Conteste a exactidão dos dados, durante o período que permita à ANGONUEVE verificar a sua exactidão;</li>
                        <li>O tratamento for ilícito e o titular se oponha à eliminação, solicitando em contrapartida a limitação da sua utilização;</li>
                        <li>A ANGONUEVE já não precisar dos dados para fins de tratamento, mas o titular necessite deles para efeitos de declaração, exercício ou defesa de direitos num processo judicial;</li>
                        <li>O titular se tiver oposto ao tratamento, até que se verifique se os motivos legítimos da ANGONUEVE prevalecem sobre os do titular.</li>
                    </ul>

                    <h3>12.5. Direito de Oposição (art. 15.º)</h3>
                    <p>O titular tem o direito de se opor a qualquer momento, por razões relacionadas com a sua situação particular, ao tratamento dos dados pessoais que lhe digam respeito com base no interesse legítimo da ANGONUEVE, incluindo a perfilagem. A ANGONUEVE cessará o tratamento, salvo se apresentar razões legítimas imperiosas que prevaleçam sobre os interesses, direitos e liberdades do titular.</p>

                    <h3>12.6. Direito à Portabilidade dos Dados (art. 16.º-A)</h3>
                    <p>O titular tem o direito de receber os dados pessoais que lhe digam respeito e que tenha fornecido à ANGONUEVE, num formato estruturado, de uso corrente e de leitura automática, e o direito de transmitir esses dados a outro responsável pelo tratamento, sem que a ANGONUEVE o impeça.</p>

                    <h3>12.7. Direito de Não Ficar Sujeito a Decisões Automatizadas</h3>
                    <p>O titular tem o direito de não ficar sujeito a nenhuma decisão tomada exclusivamente com base no tratamento automatizado, incluindo a perfilagem, que produza efeitos jurídicos que lhe digam respeito ou o afectem significativamente de forma similar.</p>

                    <h3>12.8. Como Exercer os Seus Direitos</h3>
                    <p>Para exercer qualquer um dos direitos acima descritos, o titular dos dados deve:</p>
                    <ul>
                        <li>Enviar um email para <strong>geral@angonueve.co</strong> com o assunto «Exercício de Direitos de Protecção de Dados»;</li>
                        <li>Incluir na comunicação o nome completo, email utilizado no registo e uma descrição clara do direito que pretende exercer;</li>
                        <li>Anexar cópia de documento de identificação válido para confirmação da identidade.</li>
                    </ul>
                    <p>A ANGONUEVE responderá ao pedido no prazo máximo de <strong>30 (trinta) dias</strong> a contar da recepção do pedido e da verificação da identidade do titular. Em caso de pedidos complexos ou excessivos, a ANGONUEVE reserva-se o direito de alargar o prazo até 60 dias ou cobrar uma taxa administrativa razoável.</p>

